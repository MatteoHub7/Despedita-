function handleQuizButton() {

    if (currentQuizIndex === null || quizRevealed) {

        drawQuizQuestion();

    } else {

        revealQuizAnswer();

    }

}


function drawQuizQuestion() {

    if (
        usedQuizQuestions.length >=
        quizQuestions.length
    ) {

        const reset =
            confirm(
                "Hai terminato tutte le domande. Vuoi ricominciare?"
            );

        if (reset) {
            resetQuizDeck();
        }

        return;

    }


    const available =
        quizQuestions
            .map((item, index) => index)
            .filter(
                index =>
                    !usedQuizQuestions.includes(index)
            );


    const randomPosition =
        Math.floor(
            Math.random() *
            available.length
        );


    currentQuizIndex =
        available[randomPosition];


    usedQuizQuestions.push(
        currentQuizIndex
    );


    selectedQuizAnswer = null;
    quizRevealed = false;


    const quiz =
        quizQuestions[currentQuizIndex];


    quizQuestion.textContent =
        quiz.question;


    quizOptions.innerHTML = "";

    quizResult.innerHTML = "";
    quizResult.classList.remove("visible");


    /* DOMANDA APERTA */

    if (quiz.correct === "open") {

        quizMainButton.textContent =
            "SCOPRI LA VERITÀ";

    } else {

        quiz.options.forEach(
            (option, index) => {

                const button =
                    document.createElement("button");

                button.className =
                    "quiz-option";

                button.textContent =
                    `${String.fromCharCode(65 + index)}) ${option}`;

                button.onclick =
                    () => selectQuizAnswer(
                        index,
                        button
                    );

                quizOptions.appendChild(
                    button
                );

            }
        );


        quizMainButton.textContent =
            "SCOPRI LA VERITÀ";

    }


    updateQuizCounter();


    quizCard.classList.remove(
        "animate"
    );

    void quizCard.offsetWidth;

    quizCard.classList.add(
        "animate"
    );


    vibrate();

    saveGame();

    updateHomeCounters();

}


function selectQuizAnswer(
    index,
    button
) {

    if (quizRevealed) {
        return;
    }


    selectedQuizAnswer = index;


    document
        .querySelectorAll(".quiz-option")
        .forEach(option => {

            option.classList.remove(
                "selected"
            );

        });


    button.classList.add(
        "selected"
    );

}


function revealQuizAnswer() {

    if (currentQuizIndex === null) {
        return;
    }


    const quiz =
        quizQuestions[currentQuizIndex];


    /* DOMANDA APERTA */

    if (quiz.correct === "open") {

        quizResult.innerHTML =
            `<strong>VERDETTO</strong><br>${quiz.explanation}`;

        quizResult.classList.add(
            "visible"
        );

        quizRevealed = true;

        quizMainButton.textContent =
            "PROSSIMA DOMANDA";

        vibrate();

        return;

    }


    const buttons =
        document.querySelectorAll(
            ".quiz-option"
        );


    /* NESSUNA RISPOSTA CORRETTA */

    if (quiz.correct === null) {

        buttons.forEach(button => {

            button.classList.add(
                "wrong",
                "disabled"
            );

        });


        quizResult.innerHTML =
            `<strong>NESSUNA DELLE PRECEDENTI</strong><br>${quiz.explanation}`;

    } else {

        buttons.forEach(
            (button, index) => {

                button.classList.add(
                    "disabled"
                );


                const correctIndex =
                    quiz.specialCorrectIndex ??
                    quiz.correct;


                if (
                    index ===
                    correctIndex
                ) {

                    button.classList.add(
                        "correct"
                    );

                }


                if (
                    selectedQuizAnswer !== null &&
                    index === selectedQuizAnswer &&
                    index !== correctIndex
                ) {

                    button.classList.add(
                        "wrong"
                    );

                }

            }
        );


        const correctIndex =
            quiz.specialCorrectIndex ??
            quiz.correct;


        const letter =
            String.fromCharCode(
                65 + correctIndex
            );


        const answer =
            quiz.options[
                correctIndex
            ];


        quizResult.innerHTML =
            `<strong>${letter}) ${answer}</strong><br>${quiz.explanation}`;

    }


    quizResult.classList.add(
        "visible"
    );


    quizRevealed = true;


    quizMainButton.textContent =
        "PROSSIMA DOMANDA";


    vibrate();

}


/* ==================================================
   CONTATORI
================================================== */

function updateCardCounter() {

    let used;
    let total;


    if (currentMode === "truth") {

        used =
            usedTruthCards.length;

        total =
            truthCards.length;

    } else {

        used =
            usedDareCards.length;

        total =
            dareCards.length;

    }


    cardNumber.textContent =
        `CARTA ${used} / ${total}`;


    if (used === total) {

        drawButton.textContent =
            "MAZZO TERMINATO";

    } else if (used === 0) {

        drawButton.textContent =
            "PESCA UNA CARTA";

    } else {

        drawButton.textContent =
            "PESCA ANCORA";

    }

}


function updateQuizCounter() {

    quizNumber.textContent =
        `QUIZ ${usedQuizQuestions.length} / ${quizQuestions.length}`;

}


function updateHomeCounters() {

    document
        .getElementById(
            "truth-home-counter"
        )
        .textContent =
        truthCards.length -
        usedTruthCards.length;


    document
        .getElementById(
            "dare-home-counter"
        )
        .textContent =
        dareCards.length -
        usedDareCards.length;


    document
        .getElementById(
            "quiz-home-counter"
        )
        .textContent =
        quizQuestions.length -
        usedQuizQuestions.length;

}


/* ==================================================
   RESET VERITÀ / OBBLIGO
================================================== */

function resetCurrentDeck() {

    if (!currentMode) {
        return;
    }


    const deckName =
        currentMode === "truth"
            ? "delle Verità"
            : "degli Obblighi";


    const confirmation =
        confirm(
            `Vuoi davvero resettare il mazzo ${deckName}?`
        );


    if (!confirmation) {
        return;
    }


    if (currentMode === "truth") {

        usedTruthCards = [];

    } else {

        usedDareCards = [];

    }


    cardText.textContent =
        "Mazzo resettato. Il disastro può ricominciare.";


    saveGame();

    updateCardCounter();

    updateHomeCounters();

}


/* ==================================================
   RESET QUIZ
================================================== */

function resetQuizDeck() {

    const confirmation =
        confirm(
            "Vuoi davvero resettare tutte le domande del Quiz?"
        );


    if (!confirmation) {
        return;
    }


    usedQuizQuestions = [];

    currentQuizIndex = null;

    selectedQuizAnswer = null;

    quizRevealed = false;


    resetQuizDisplay();

    saveGame();

    updateHomeCounters();

}


/* ==================================================
   RESET DISPLAY QUIZ
================================================== */

function resetQuizDisplay() {

    currentQuizIndex = null;

    selectedQuizAnswer = null;

    quizRevealed = false;


    quizQuestion.textContent =
        "Premi il pulsante per iniziare.";


    quizOptions.innerHTML = "";

    quizResult.innerHTML = "";

    quizResult.classList.remove(
        "visible"
    );


    quizMainButton.textContent =
        "PESCA UNA DOMANDA";


    updateQuizCounter();

}


