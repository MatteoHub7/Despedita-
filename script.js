/* ==================================================
   LOCAL STORAGE
================================================== */

function loadGame() {

    try {

        usedTruthCards =
            JSON.parse(
                localStorage.getItem("despedida_truth")
            ) || [];

        usedDareCards =
            JSON.parse(
                localStorage.getItem("despedida_dare")
            ) || [];

        usedQuizQuestions =
            JSON.parse(
                localStorage.getItem("despedida_quiz")
            ) || [];

    } catch {

        usedTruthCards = [];
        usedDareCards = [];
        usedQuizQuestions = [];

    }

    updateHomeCounters();

}


function saveGame() {

    localStorage.setItem(
        "despedida_truth",
        JSON.stringify(usedTruthCards)
    );

    localStorage.setItem(
        "despedida_dare",
        JSON.stringify(usedDareCards)
    );

    localStorage.setItem(
        "despedida_quiz",
        JSON.stringify(usedQuizQuestions)
    );

}


/* ==================================================
   HOME / MODALITÀ
================================================== */

function startGame(mode) {

    currentMode = mode;

    homeScreen.classList.remove("active");
    gameScreen.classList.remove("active");
    quizScreen.classList.remove("active");


    if (mode === "quiz") {

        quizScreen.classList.add("active");

        resetQuizDisplay();

        return;

    }


    gameScreen.classList.add("active");


    if (mode === "truth") {

        gameTitle.textContent = "VERITÀ";
        cardType.textContent = "VERITÀ";
        cardIcon.textContent = "†";

        drawButton.classList.remove("dare-mode");

    } else {

        gameTitle.textContent = "OBBLIGO";
        cardType.textContent = "OBBLIGO";
        cardIcon.textContent = "⚰";

        drawButton.classList.add("dare-mode");

    }


    cardText.textContent =
        "Premi il pulsante per pescare.";

    updateCardCounter();

}


function goHome() {

    gameScreen.classList.remove("active");
    quizScreen.classList.remove("active");

    homeScreen.classList.add("active");

    currentMode = null;

    updateHomeCounters();

}


